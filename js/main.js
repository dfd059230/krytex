// city markers on the world map (Moscow, Guangzhou, Bratislava)
function setupCities(){
  var svg = document.querySelector('#krxMap svg.svgMap-map-image') || document.querySelector('#krxMap svg');
  if(!svg) return;
  function bbox(code){
    var el = svg.querySelector('.svgMap-country[data-id="' + code + '"]');
    if(!el) return null;
    try{ return el.getBBox(); }catch(e){ return null; }
  }
  // Each city is positioned RELATIVE to its anchor country's outline:
  // fx/fy = fraction of the bbox (west->east / north->south), extrapolation allowed.
  // Computed from real geo bounds of each anchor country vs city lat/lon.
  var cities = [
    { key:'city.ba', dx:-14, dy:-12, anchor:'end',
      refs:[ {c:'SK', fx:0.049, fy:0.776} ] },                       // Bratislava: SW corner of Slovakia
    { key:'city.msk', dx:14, dy:6,
      refs:[ {c:'BY', fx:1.506, fy:0.084},                            // Moscow: east of Belarus, same latitude band
             {c:'EE', fx:1.95, fy:0.62} ] },                          // fallback: relative to Estonia
    { key:'city.gz', dx:14, dy:6,
      refs:[ {c:'HK', fx:-1.03, fy:-1.39},                            // Guangzhou: just NW of Hong Kong
             {c:'TW', fx:-3.45, fy:0.64} ] }                          // fallback: west of Taiwan
  ];
  function locate(city){
    for(var i=0;i<city.refs.length;i++){
      var r = city.refs[i], b = bbox(r.c);
      if(b && b.width > 0) return { x: b.x + b.width*r.fx, y: b.y + b.height*r.fy };
    }
    return null;
  }
  var NS = 'http://www.w3.org/2000/svg';
  var anyCountry = svg.querySelector('.svgMap-country');
  var container = anyCountry ? anyCountry.parentNode : svg;
  window.drawKrxCities = function(){
    var d = I18N[lang];
    var old = container.querySelector('#krxCities');
    if(old) old.remove();
    var g = document.createElementNS(NS, 'g');
    g.setAttribute('id', 'krxCities');
    g.setAttribute('pointer-events', 'none');
    cities.forEach(function(c){
      var p = locate(c);
      if(!p) return;
      var pulse = document.createElementNS(NS, 'circle');
      pulse.setAttribute('cx', p.x); pulse.setAttribute('cy', p.y);
      pulse.setAttribute('r', 7); pulse.setAttribute('fill', 'none');
      pulse.setAttribute('stroke', '#ffffff'); pulse.setAttribute('stroke-width', 2);
      var a1 = document.createElementNS(NS, 'animate');
      a1.setAttribute('attributeName','r'); a1.setAttribute('from','7'); a1.setAttribute('to','22');
      a1.setAttribute('dur','1.8s'); a1.setAttribute('repeatCount','indefinite');
      var a2 = document.createElementNS(NS, 'animate');
      a2.setAttribute('attributeName','opacity'); a2.setAttribute('from','.9'); a2.setAttribute('to','0');
      a2.setAttribute('dur','1.8s'); a2.setAttribute('repeatCount','indefinite');
      pulse.appendChild(a1); pulse.appendChild(a2);
      var dot = document.createElementNS(NS, 'circle');
      dot.setAttribute('cx', p.x); dot.setAttribute('cy', p.y); dot.setAttribute('r', 7);
      dot.setAttribute('fill', '#ffffff'); dot.setAttribute('stroke', '#0a0a0b'); dot.setAttribute('stroke-width', 2.5);
      var t = document.createElementNS(NS, 'text');
      t.setAttribute('x', p.x + c.dx); t.setAttribute('y', p.y + c.dy);
      if(c.anchor) t.setAttribute('text-anchor', c.anchor);
      t.setAttribute('fill', '#ffffff');
      t.setAttribute('font-size', '26');
      t.setAttribute('font-weight', '700');
      t.setAttribute('font-family', "'Gotham Pro','Noto Sans SC',sans-serif");
      t.setAttribute('paint-order', 'stroke');
      t.setAttribute('stroke', '#0a0a0b'); t.setAttribute('stroke-width', '5');
      t.textContent = d[c.key] || '';
      g.appendChild(pulse); g.appendChild(dot); g.appendChild(t);
    });
    container.appendChild(g);
  };
  window.drawKrxCities();
  // keep city markers above hovered countries (svgMap re-appends paths on hover)
  container.addEventListener('mouseover', function(){
    var g = container.querySelector('#krxCities');
    if(g && g !== container.lastElementChild) container.appendChild(g);
  });
  var _origApply = applyLang;
  applyLang = function(l){ _origApply(l); if(window.drawKrxCities) window.drawKrxCities(); };
}


